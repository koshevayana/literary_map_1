    Author = apps.get_model('literature', 'Author')
    Work = apps.get_model('literature', 'Work')

    grades = {number: Grade.objects.create(number=number) for number in range(1, 12)}

    for position, data in enumerate(AUTHORS, start=1):
        data = dict(data)
        works = data.pop('works')
        grade_numbers = data.pop('grades')
        for key in ('map_x', 'map_y'):
            if data[key] is not None:
                data[key] = Decimal(data[key])
        author = Author.objects.create(position=position, **data)
        Work.objects.bulk_create(
            Work(author=author, title=title, position=index) for index, title in enumerate(works, start=1)
        )
        author.grades.set(grades[number] for number in grade_numbers)


